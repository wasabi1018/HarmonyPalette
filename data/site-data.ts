export const getCharacter = (id: string) => characters.find((character) => character.id === id);

export const getCharactersForSchedule = (schedule: GreetingSchedule) =>
  schedule.characterIds.map((id) => getCharacter(id)).filter(Boolean) as Character[];

export const getNextScheduleForCharacter = (characterId: string) =>
  schedules
    .filter((schedule) => schedule.characterIds.includes(characterId))
    .sort((a, b) => `${a.date}${a.startTime}`.localeCompare(`${b.date}${b.startTime}`))[0];
